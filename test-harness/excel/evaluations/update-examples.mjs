// @ts-check
/**
 * update-examples.mjs — publish the real-data gallery as the tracked examples.
 *
 * Copies every rendered chart from out/real-gallery (see real-gallery.mjs)
 * into evaluations/examples/ and the site's Excel gallery assets, writes a
 * manifest both read, regenerates examples/README.md, and publishes the
 * exported workbook (export-workbook.mjs) for download from the site.
 *
 *   node evaluations/real-gallery.mjs
 *   node evaluations/export-workbook.mjs
 *   node evaluations/update-examples.mjs
 */

import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..', '..');
const galleryDir = join(here, 'out', 'real-gallery');
const examplesDir = join(here, 'examples');
const siteAssetsDir = join(repo, 'site', 'src', 'assets', 'excel-gallery');
const siteDownloadDir = join(repo, 'site', 'public', 'excel');
const workbook = join(galleryDir, 'flint-excel-gallery.xlsx');

/** @typedef {{ id: string, title: string, chartType: string, excelType: string, size: string, source?: string, ok?: boolean }} GalleryEntry */

/** @type {GalleryEntry[]} */
const summary = JSON.parse(readFileSync(join(galleryDir, 'summary.json'), 'utf8')).filter((/** @type {GalleryEntry} */ entry) => entry.ok);
if (summary.length === 0) throw new Error('No rendered charts in out/real-gallery; run real-gallery.mjs first.');
if (!existsSync(workbook)) throw new Error('Missing out/real-gallery/flint-excel-gallery.xlsx; run export-workbook.mjs first.');

const manifest = summary.map((entry) => ({
  id: entry.id,
  title: entry.title,
  label: entry.title.split(' — ')[0].replace(/\s*\([^)]*\)\s*$/, ''),
  chartType: entry.chartType,
  excelType: entry.excelType,
  size: entry.size,
  source: entry.source ?? '',
}));

for (const dir of [examplesDir, siteAssetsDir]) {
  mkdirSync(dir, { recursive: true });
  for (const file of readdirSync(dir)) {
    if (file.endsWith('.png') || file === 'manifest.json') rmSync(join(dir, file));
  }
  for (const entry of manifest) copyFileSync(join(galleryDir, `${entry.id}.excel.png`), join(dir, `${entry.id}.png`));
  writeFileSync(join(dir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
}
mkdirSync(siteDownloadDir, { recursive: true });
copyFileSync(workbook, join(siteDownloadDir, 'flint-excel-gallery.xlsx'));

const cells = manifest.map((entry) =>
  `<td width="33%" align="center"><strong>${entry.label}</strong><br><br><img src="${entry.id}.png" alt="${entry.title}, a native Excel ${entry.excelType} chart generated by Flint" width="100%"></td>`);
const rows = [];
for (let index = 0; index < cells.length; index += 3) rows.push(`<tr>\n${cells.slice(index, index + 3).join('\n')}\n</tr>`);
const table = manifest.map((entry) => `| ${entry.title} | ${entry.chartType} | \`${entry.excelType}\` | ${entry.source.replace(/\|/g, '\\|')} |`);

writeFileSync(join(examplesDir, 'README.md'), `# Native Excel chart examples

Flint generates native Excel charts from semantic chart specs. These ${manifest.length} charts are drawn from real datasets, rendered in Excel for Mac through Office.js, and remain editable in Excel.

The same charts, each on its own sheet beside its data, are in [flint-excel-gallery.xlsx](../../../../site/public/excel/flint-excel-gallery.xlsx).

<table>
${rows.join('\n')}
</table>

## About these charts

- Each chart is a native Excel chart object, not a canvas overlay or pasted image.
- Size, axes, date ticks, number formats and bar spacing come from Flint's layout; colours and fonts are Excel's own.
- Data, formatting, titles, axes, and series can be edited in Excel.

<details>
<summary><strong>How these examples were produced</strong></summary>

These images are unedited \`Chart.getImage()\` captures from the real Excel for Mac Office.js worker, at the size \`assembleExcel\` chooses. Regenerate them with:

\`\`\`bash
node evaluations/real-gallery.mjs
node evaluations/export-workbook.mjs
node evaluations/update-examples.mjs
\`\`\`

| Chart | Flint chart type | Native Excel chart | Data source |
| --- | --- | --- | --- |
${table.join('\n')}

</details>
`);

console.log(`published ${manifest.length} charts to examples/ and site/src/assets/excel-gallery/, and the workbook to site/public/excel/`);
