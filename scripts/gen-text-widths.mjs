// Measures the width of each printable ASCII character, in em, for the font families the theme
// presets name, in headless Chrome's canvas, and writes them as a table the planner reads so a
// plan comes out the same in a browser and in Node. Run: npm run gen:text-widths
// (CHROME_PATH selects the browser; families the machine lacks are left out of the table.)
import puppeteer from 'puppeteer-core';
import { writeFileSync } from 'node:fs';

const FAMILIES = [
    'Helvetica Neue', 'Helvetica', 'Arial', 'Verdana', 'Arial Black', 'Segoe UI', 'Georgia', 'Comic Sans MS', 'Comic Neue',
    'Chalkboard SE', 'Marker Felt', 'SF Pro Display', 'SF Pro Text', '-apple-system', 'BlinkMacSystemFont',
    'system-ui', 'sans-serif', 'serif', 'cursive',
];
const GENERIC = new Set(['sans-serif', 'serif', 'cursive', 'system-ui', '-apple-system', 'BlinkMacSystemFont']);
const executablePath = process.env.CHROME_PATH
    ?? `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1223/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing`;
const browser = await puppeteer.launch({ executablePath, headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage();
await page.setContent('<html><body></body></html>');
const table = await page.evaluate(async (families, generic) => {
    const canvas = document.createElement('canvas').getContext('2d');
    const out = {};
    for (const family of families) {
        const css = generic.includes(family) ? family : `"${family}"`;
        if (!generic.includes(family)) {
            await document.fonts.load(`100px ${css}`);
            if (!document.fonts.check(`100px ${css}`)) continue;
            // A family the machine lacks resolves to the fallback; compare against a fallback that differs.
            canvas.font = `100px ${css}, monospace`;
            const probe = canvas.measureText('mmmmmlllllWWW').width;
            canvas.font = '100px monospace';
            if (Math.abs(probe - canvas.measureText('mmmmmlllllWWW').width) < 0.01) continue;
        }
        out[family] = {};
        for (const weight of ['normal', 'bold']) {
            canvas.font = `${weight} 100px ${css}`;
            const widths = [];
            for (let code = 32; code < 127; code += 1) widths.push(Math.round(canvas.measureText(String.fromCharCode(code)).width * 10) / 1000);
            out[family][weight] = widths;
        }
    }
    return out;
}, FAMILIES, [...GENERIC]);
await browser.close();
const body = Object.entries(table)
    .map(([family, weights]) => `    ${JSON.stringify(family)}: {\n${Object.entries(weights).map(([weight, widths]) => `        ${weight}: [${widths.join(', ')}],`).join('\n')}\n    },`)
    .join('\n');
writeFileSync('packages/flint-js/src/core/text-widths.generated.ts', `// Generated by scripts/gen-text-widths.mjs; do not edit.

/** Widths of the printable ASCII characters (32 to 126), in em, by font family and weight. */
export const TEXT_WIDTHS: Record<string, Record<'normal' | 'bold', number[]>> = {
${body}
};
`);
console.log(`families: ${Object.keys(table).join(', ')}`);
