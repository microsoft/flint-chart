/**
 * Builds packages/flint-js/src/geo/world-bank-{coarse,medium}.json, the default world maps, from
 * the World Bank Official Boundaries TopoJSON that Data Formulator builds (CC BY 4.0; see
 * data-formulator/src/maps/data/world-bank/build.sh, which simplifies the World Bank's Admin 0 and
 * Non-Determined Legal Status Areas layers to levels of detail).
 *
 *   node scripts/build-world-bank.mjs [path/to/data-formulator/src/maps/data/world-bank]
 *
 * Flint joins the world by ISO 3166-1 numeric id, so each country's alpha-3 id becomes its numeric
 * one; a place without one (Kosovo, Clipperton) keeps its alpha-3 code. France's overseas
 * departments, which the source names France, take France's id. Areas of non-determined legal status
 * keep `ndlsa: true`, and the borders they share are a mesh of their own, `disputed`, drawn dotted.
 *
 * Also writes packages/flint-js/src/chart-types/world-bank-ids.ts: the ISO numeric ids the map draws,
 * and the body bounds of those the Natural Earth bounds table (geo-bounds.ts) lacks.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { feature, meshArcs } from 'topojson-client';
import { countryBody } from './lib/country-body.mjs';

const SOURCE = process.argv[2] ?? fileURLToPath(new URL('../../data-formulator/src/maps/data/world-bank', import.meta.url));
const OUT = fileURLToPath(new URL('../packages/flint-js/src/geo/', import.meta.url));
const GEO_TS = fileURLToPath(new URL('../packages/flint-js/src/chart-types/geo.ts', import.meta.url));
const BOUNDS_TS = fileURLToPath(new URL('../packages/flint-js/src/chart-types/geo-bounds.ts', import.meta.url));
const IDS_TS = fileURLToPath(new URL('../packages/flint-js/src/chart-types/world-bank-ids.ts', import.meta.url));

// Flint's country table (alpha-3 → numeric), read from its source.
const geo = await readFile(GEO_TS, 'utf8');
const table = geo.slice(geo.indexOf('const COUNTRIES'), geo.indexOf('];', geo.indexOf('const COUNTRIES')));
const NUMERIC = new Map([...table.matchAll(/\[(\d+), '(?:[^'\\]|\\.)*', '\w*', '(\w+)'\]/g)].map((m) => [m[2], Number(m[1])]));

// ISO 3166-1 numeric codes of the territories Flint's table leaves out.
const TERRITORIES = {
    ABW: 533, AIA: 660, ALA: 248, ASM: 16, BES: 535, BLM: 652, BMU: 60, BVT: 74, CCK: 166, COK: 184,
    CUW: 531, CXR: 162, CYM: 136, FRO: 234, GGY: 831, GIB: 292, GUM: 316, HMD: 334, IMN: 833, IOT: 86,
    JEY: 832, MAF: 663, MNP: 580, MSR: 500, NFK: 574, NIU: 570, PCN: 612, PYF: 258, SGS: 239, SHN: 654,
    SJM: 744, SPM: 666, SXM: 534, TCA: 796, TKL: 772, UMI: 581, VGB: 92, VIR: 850, WLF: 876,
    // France's overseas departments are France.
    GLP: 250, GUF: 250, MTQ: 250, MYT: 250, REU: 250,
};

const numericId = (id) => NUMERIC.get(id) ?? TERRITORIES[id] ?? id;

const known = new Set([...(await readFile(BOUNDS_TS, 'utf8')).matchAll(/^\s*\[(\d+),/gm)].map((m) => Number(m[1])));
for (const level of ['coarse', 'medium']) {
    const topology = JSON.parse(await readFile(`${SOURCE}/${level}.json`, 'utf8'));
    const countries = topology.objects.countries;
    for (const geometry of countries.geometries) {
        const { name, ndlsa } = geometry.properties ?? {};
        geometry.id = ndlsa && String(geometry.id).startsWith('NDLSA-') ? geometry.id : numericId(geometry.id);
        geometry.properties = { name, ...(ndlsa ? { ndlsa: true } : {}) };
    }
    const undetermined = (g) => Boolean(g.properties?.ndlsa);
    topology.objects.disputed = meshArcs(topology, countries, (a, b) => a !== b && (undetermined(a) || undetermined(b)));
    const unmapped = countries.geometries.filter((g) => typeof g.id === 'string' && !g.id.startsWith('NDLSA-')).map((g) => g.id);
    await writeFile(`${OUT}world-bank-${level}.json`, JSON.stringify(topology));
    console.log(`world-bank-${level}.json: ${countries.geometries.length} features; kept alpha-3: ${unmapped.join(', ') || 'none'}`);
    if (level !== 'coarse') continue;

    const ids = [...new Set(countries.geometries.map((g) => g.id).filter((id) => typeof id === 'number'))].sort((a, b) => a - b);
    const extra = [];
    for (const id of ids.filter((id) => !known.has(id))) {
        const body = countryBody(countries.geometries.filter((g) => g.id === id).map((g) => feature(topology, g).geometry));
        if (body) extra.push([id, ...body]);
    }
    await writeFile(IDS_TS, `// Copyright (c) Microsoft Corporation.
// Licensed under the MIT License.

// Generated by scripts/build-world-bank.mjs. Do not edit.

/** The ISO 3166-1 numeric ids the World Bank world map draws (Kosovo and Clipperton, which have none, aside). */
export const WORLD_BANK_IDS: ReadonlySet<number> = new Set([${ids.join(', ')}]);

/** [id, west, south, east, north] of each body (scripts/lib/country-body.mjs) the Natural Earth bounds table lacks: the territories it leaves out. */
export const WORLD_BANK_EXTRA_BOUNDS: ReadonlyArray<readonly [number, number, number, number, number]> = [
${extra.map((row) => `    [${row.join(', ')}],`).join('\n')}
];
`);
    console.log(`world-bank-ids.ts: ${ids.length} ids, ${extra.length} extra bounds`);
}
