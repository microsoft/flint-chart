/**
 * Builds packages/flint-js/src/chart-types/geo-bounds.ts: the bounds of each country's body (its
 * largest polygon and the large ones near it) in Natural Earth's world, keyed by ISO 3166-1 numeric id.
 * The map plan frames regional data with them without loading the geometry.
 *
 *   node scripts/build-geo-bounds.mjs [path/to/world-110m.json]
 *
 * Without a path, the TopoJSON is fetched from the URL the Vega-Lite map template uses.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';
import { countryBody } from './lib/country-body.mjs';

const WORLD_URL = 'https://vega.github.io/vega-lite/data/world-110m.json';
const OUT = fileURLToPath(new URL('../packages/flint-js/src/chart-types/geo-bounds.ts', import.meta.url));

const source = process.argv[2];
const topology = source
    ? JSON.parse(await readFile(source, 'utf8'))
    : await (await fetch(WORLD_URL)).json();

const rows = [];
for (const country of feature(topology, topology.objects.countries).features) {
    if (!country.geometry || country.id == null) continue;
    const body = countryBody([country.geometry]);
    if (body) rows.push([Number(country.id), ...body]);
}
rows.sort((a, b) => a[0] - b[0]);

const body = rows.map((row) => `    [${row.join(', ')}],`).join('\n');
await writeFile(OUT, `// Copyright (c) Microsoft Corporation.
// Licensed under the MIT License.

// Generated by scripts/build-geo-bounds.mjs from Vega's world-110m.json (Natural Earth). Do not edit.

/**
 * Each country's body — its largest polygon and the large ones near it (scripts/lib/country-body.mjs)
 * — as [ISO 3166-1 numeric id, west, south, east, north] in degrees. A body that crosses the
 * antimeridian has west > east.
 */
export const COUNTRY_BOUNDS: ReadonlyArray<readonly [number, number, number, number, number]> = [
${body}
];
`);
console.log(`wrote ${rows.length} countries to ${OUT}`);
