/**
 * Gallery generators for CanvasXpress-exclusive scientific charts — chart types
 * the generic grammar does not define and no other flint backend can render:
 *   - Volcano: differential expression (log2 fold-change vs significance).
 *   - Venn: set relationships by precomputed region counts.
 *   - Network: a node-link graph from edge rows.
 *   - Correlation: a correlation matrix over numeric variables.
 *   - Sankey: multi-stage flows (an alluvial diagram).
 *   - Chord: entity-to-entity relationships around a circle.
 *   - Circos: a circular genomic track (chromosome ideogram + data ring).
 *
 * Each introduces its own domain semantic encodings (channels the generic model
 * lacks). Data is synthetic but deterministic (a seeded RNG) so baselines hold.
 */

