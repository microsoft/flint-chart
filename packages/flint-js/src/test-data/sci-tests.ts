export function genUpSetTests(): TestCase[] {
    const rng = makeRng(54321);
    const sets = ['Up in Tumor', 'Up in Normal', 'Up in Metastasis', 'Druggable', 'Essential'];
    // Per-set membership probability — varied so intersections differ in size.
    const prob = [0.42, 0.38, 0.33, 0.22, 0.18];
    const rows: Array<{ gene: string; set: string; member: number }> = [];
    for (let i = 0; i < 120; i++) {
        const gene = 'G' + (i + 1);
        // Guarantee each gene is in at least one set so no empty rows.
        let any = false;
        const flags = sets.map((_, s) => { const m = rng() < prob[s] ? 1 : 0; if (m) any = true; return m; });
        if (!any) flags[Math.floor(rng() * sets.length)] = 1;
        for (let s = 0; s < sets.length; s++) rows.push({ gene, set: sets[s], member: flags[s] });
    }
    const meta = {
        gene: { type: Type.String, semanticType: 'Category' as const, levels: [] },
        set: { type: Type.String, semanticType: 'Category' as const, levels: [] },
        member: { type: Type.Number, semanticType: 'Count' as const, levels: [] },
    };
    const encodingMap: Record<string, any> = {
        y: makeEncodingItem('gene'), x: makeEncodingItem('set'), value: makeEncodingItem('member'),
    };
    return [{
        title: 'Gene-set intersections (UpSet)',
        description:
            'An UpSet plot: the sizes of every intersection of five gene sets, where a '
            + 'Venn diagram would be unreadable. Bars give intersection sizes; the dot '
            + 'matrix below names which sets each bar combines. Built from a binary '
            + 'membership matrix — CanvasXpress derives the intersections itself.',
        tags: ['upset', 'sets', 'intersection', 'scientific', 'omics', 'gallery'],
        chartType: 'UpSet Plot',
        data: rows,
        fields: [makeField('gene'), makeField('set'), makeField('member')],
        metadata: meta,
        encodingMap,
    }];
}

