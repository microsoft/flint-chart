/** Tiny deterministic LCG so the synthetic datasets never drift between runs. */
function makeRng(seed: number): () => number {
    let state = seed >>> 0;
    return () => {
        state = (state * 1664525 + 1013904223) >>> 0;
        return state / 0x100000000;
    };
}

